function getPageKey() {
  return document.body.dataset.page || 'home';
}

function getTranslation(key, page, lang) {
  if (lang === 'de' && translations.de && translations.de[key]) {
    return translations.de[key];
  }
  if (translations[page] && translations[page][key]) {
    return translations[page][key];
  }
  if (translations.common && translations.common[key]) {
    return translations.common[key];
  }
  return '';
}

function applyLanguage(lang) {
  const page = getPageKey();
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach((el) => {
    const key = el.dataset.i18n;
    const attr = el.dataset.i18nAttr;
    const value = getTranslation(key, page, lang);
    if (!value) return;
    if (attr) {
      el.setAttribute(attr, value);
    } else {
      el.textContent = value;
    }
  });

  const langToggle = document.getElementById('langToggle');
  if (langToggle) {
    langToggle.textContent = lang === 'de' ? 'EN' : 'DE';
  }
  document.documentElement.lang = lang;
  localStorage.setItem('siteLanguage', lang);
}

function initLanguageToggle() {
  const langToggle = document.getElementById('langToggle');
  if (!langToggle) return;
  const storedLang = localStorage.getItem('siteLanguage');
  const currentLang = storedLang === 'de' ? 'de' : 'en';
  applyLanguage(currentLang);

  langToggle.addEventListener('click', () => {
    const nextLang = document.documentElement.lang === 'de' ? 'en' : 'de';
    applyLanguage(nextLang);
  });
}

function initNavToggle() {
  const toggle = document.getElementById('navToggle');
  const links = document.querySelector('.navbar_links');
  const closeBtn = document.getElementById('navClose');
  if (!toggle || !links) return;

  toggle.addEventListener('click', () => {
    const isOpen = links.classList.toggle('open');
    toggle.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
  });

  if (closeBtn) {
    closeBtn.addEventListener('click', () => {
      if (links.classList.contains('open')) {
        links.classList.remove('open');
        toggle.setAttribute('aria-expanded', 'false');
      }
    });
  }

  // Close menu when clicking a link
  links.querySelectorAll('a').forEach((a) => {
    a.addEventListener('click', () => {
      if (links.classList.contains('open')) {
        links.classList.remove('open');
        toggle.setAttribute('aria-expanded', 'false');
      }
    });
  });

  // Ensure menu is closed when resizing above breakpoint
  window.addEventListener('resize', () => {
    if (window.innerWidth > 800 && links.classList.contains('open')) {
      links.classList.remove('open');
      toggle.setAttribute('aria-expanded', 'false');
    }
  });
}

function initContactForm() {
  const form = document.getElementById('contactForm');
  const status = document.getElementById('formStatus');
  if (!form || !status) return;

  form.addEventListener('submit', async (event) => {
    event.preventDefault();

    const submitButton = form.querySelector('button[type="submit"]');
    const originalLabel = submitButton ? submitButton.textContent : 'Submit';

    status.textContent = 'Sending your message...';
    status.className = 'form-status';

    if (submitButton) {
      submitButton.disabled = true;
      submitButton.textContent = 'Sending...';
    }

    try {
      const formData = new FormData(form);
      const response = await fetch(form.action, {
        method: form.method,
        body: formData
      });
      const result = await response.json();

      if (!response.ok || !result.success) {
        throw new Error(result.message || 'Unable to send your message right now.');
      }

      form.reset();
      status.textContent = 'Thanks! Your message has been sent.';
      status.classList.add('success');
    } catch (error) {
      status.textContent = error.message || 'Unable to send your message right now.';
      status.classList.add('error');
    } finally {
      if (submitButton) {
        submitButton.disabled = false;
        submitButton.textContent = originalLabel;
      }
    }
  });
}

window.addEventListener('DOMContentLoaded', () => {
  initLanguageToggle();
  initNavToggle();
  initContactForm();
});
